#!/usr/bin/env python3
"""Summarize PENGWIN MedSAM/MoE evaluation CSV files.

Usage:
    python evaluation/summarize_eval_csv.py data/medsam-predictions/eval_overlap_full.csv

Optional:
    python evaluation/summarize_eval_csv.py \
      data/medsam-predictions/eval_boundary_1000.csv \
      --summary-csv data/medsam-predictions/eval_boundary_1000_summary.csv
"""

from __future__ import annotations

import argparse
import math
from pathlib import Path

import numpy as np
import pandas as pd


DEFAULT_METRICS = ["dice", "iou", "hd95", "assd"]
DEFAULT_CLASS_ORDER = ["SA", "LI", "RI"]
DEFAULT_SIZE_ORDER = ["small", "large", "unknown"]


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "csv_path",
        type=Path,
        help="Path to evaluation CSV generated by evaluate_medsam_pengwin.py.",
    )
    parser.add_argument(
        "--summary-csv",
        type=Path,
        default=None,
        help="Optional path to save compact summary table as CSV.",
    )
    parser.add_argument(
        "--metrics",
        nargs="+",
        default=DEFAULT_METRICS,
        help="Metric columns to summarize. Defaults to dice iou hd95 assd.",
    )
    return parser.parse_args()


def fmt_value(value: float) -> str:
    if pd.isna(value) or not math.isfinite(float(value)):
        return "nan"
    return f"{float(value):.4f}"


def available_metrics(frame: pd.DataFrame, requested_metrics: list[str]) -> list[str]:
    return [metric for metric in requested_metrics if metric in frame.columns]


def get_area_threshold_text(frame: pd.DataFrame) -> str:
    if "area_threshold_1024" not in frame.columns or frame.empty:
        return "not stored"

    values = frame["area_threshold_1024"].dropna().unique()

    if len(values) == 0:
        return "nan"

    if len(values) == 1:
        return str(values[0])

    return f"multiple values ({len(values)} unique)"


def summarize_group(
    frame: pd.DataFrame,
    metrics: list[str],
    group_type: str,
    group_name: str,
) -> dict:
    row = {
        "group_type": group_type,
        "group": group_name,
        "n": len(frame),
    }

    for metric in metrics:
        row[f"{metric}_mean"] = frame[metric].mean(skipna=True)
        row[f"{metric}_median"] = frame[metric].median(skipna=True)

    return row


def build_summary_rows(frame: pd.DataFrame, metrics: list[str]) -> list[dict]:
    rows: list[dict] = []

    rows.append(summarize_group(frame, metrics, "overall", "overall"))

    if "category_name" in frame.columns:
        for category in DEFAULT_CLASS_ORDER:
            subset = frame[frame["category_name"] == category]
            if not subset.empty:
                rows.append(summarize_group(subset, metrics, "class", category))

        other_categories = sorted(
            set(frame["category_name"].dropna().astype(str)) - set(DEFAULT_CLASS_ORDER)
        )
        for category in other_categories:
            subset = frame[frame["category_name"].astype(str) == category]
            if not subset.empty:
                rows.append(summarize_group(subset, metrics, "class", category))

    if "size_group" in frame.columns:
        for size_group in DEFAULT_SIZE_ORDER:
            subset = frame[frame["size_group"] == size_group]
            if not subset.empty:
                rows.append(summarize_group(subset, metrics, "size", size_group))

        other_sizes = sorted(
            set(frame["size_group"].dropna().astype(str)) - set(DEFAULT_SIZE_ORDER)
        )
        for size_group in other_sizes:
            subset = frame[frame["size_group"].astype(str) == size_group]
            if not subset.empty:
                rows.append(summarize_group(subset, metrics, "size", size_group))

    if {"category_name", "size_group"}.issubset(frame.columns):
        preferred_pairs = [
            ("SA", "small"),
            ("SA", "large"),
            ("LI", "small"),
            ("LI", "large"),
            ("RI", "small"),
            ("RI", "large"),
        ]

        seen_pairs = set()

        for category, size_group in preferred_pairs:
            subset = frame[
                (frame["category_name"] == category)
                & (frame["size_group"] == size_group)
            ]
            if not subset.empty:
                rows.append(
                    summarize_group(
                        subset,
                        metrics,
                        "class_size",
                        f"{category}/{size_group}",
                    )
                )
                seen_pairs.add((category, size_group))

        all_pairs = (
            frame[["category_name", "size_group"]]
            .dropna()
            .astype(str)
            .drop_duplicates()
            .itertuples(index=False, name=None)
        )

        for category, size_group in sorted(all_pairs):
            if (category, size_group) in seen_pairs:
                continue

            subset = frame[
                (frame["category_name"].astype(str) == category)
                & (frame["size_group"].astype(str) == size_group)
            ]
            if not subset.empty:
                rows.append(
                    summarize_group(
                        subset,
                        metrics,
                        "class_size",
                        f"{category}/{size_group}",
                    )
                )

    return rows


def print_table(title: str, rows: list[dict], metrics: list[str], group_type: str) -> None:
    selected = [row for row in rows if row["group_type"] == group_type]

    print(f"\n{title}")

    if not selected:
        print("No rows.")
        return

    header = f"{'group':<25} {'n':>10}"
    for metric in metrics:
        header += f" {metric + '_mean':>14}"
    print(header)
    print("-" * len(header))

    for row in selected:
        line = f"{row['group']:<25} {int(row['n']):>10}"
        for metric in metrics:
            line += f" {fmt_value(row[f'{metric}_mean']):>14}"
        print(line)


def main() -> int:
    args = parse_args()

    if not args.csv_path.exists():
        raise FileNotFoundError(f"CSV not found: {args.csv_path}")

    frame = pd.read_csv(args.csv_path)
    metrics = available_metrics(frame, args.metrics)

    if not metrics:
        raise RuntimeError(
            f"No requested metric columns found. Requested: {args.metrics}. "
            f"CSV columns: {list(frame.columns)}"
        )

    image_count = (
        frame["sample_name"].nunique()
        if "sample_name" in frame.columns
        else "not stored"
    )

    fragment_count = len(frame)

    empty_predictions = (
        int((frame["pred_area"] == 0).sum())
        if "pred_area" in frame.columns
        else "not stored"
    )

    empty_gt = (
        int((frame["gt_area"] == 0).sum())
        if "gt_area" in frame.columns
        else "not stored"
    )

    area_threshold = get_area_threshold_text(frame)

    summary_rows = build_summary_rows(frame, metrics)

    print("Evaluation summary")
    print("=" * 90)
    print(f"CSV: {args.csv_path}")
    print(f"Image records evaluated: {image_count}")
    print(f"Fragment rows written: {fragment_count}")
    print("Failed records: not stored in CSV")
    print(f"Empty predictions: {empty_predictions}")
    print(f"Empty GT masks: {empty_gt}")
    print(f"Area threshold on 1024 grid: {area_threshold}")

    print_table("Overall mean metrics:", summary_rows, metrics, "overall")
    print_table("Per-class mean metrics:", summary_rows, metrics, "class")
    print_table("Per-size mean metrics:", summary_rows, metrics, "size")
    print_table(
        "Per-class and per-size mean metrics:",
        summary_rows,
        metrics,
        "class_size",
    )

    print("=" * 90)

    if args.summary_csv is not None:
        args.summary_csv.parent.mkdir(parents=True, exist_ok=True)
        pd.DataFrame(summary_rows).to_csv(args.summary_csv, index=False)
        print(f"\nSaved summary CSV: {args.summary_csv}")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())